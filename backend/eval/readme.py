"""Render the README results block from ``results/metrics.json`` (and ``benchmark.json``)."""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

START = "<!-- RESULTS:START (generated by scripts/update_readme.py from results/*.json; do not edit) -->"
END = "<!-- RESULTS:END -->"
MAIN_MODELS = (
    "rule_requests_per_60s",
    "isolation_forest",
    "combined_rule_or_isolation_forest",
)


def _cell(r: dict, key: str) -> str:
    return f"{r[key]['mean']:.3f} ± {r[key]['std']:.3f}"


def render(metrics: dict, benchmark: dict | None) -> str:
    """Return the markdown block placed between the README markers."""
    d = metrics["dataset"]
    p = metrics["protocol"]
    lines = [
        START,
        "",
        f"Dataset: AIT-LDSv2 `russellmitchell`, Apache access log of `intranet_server` "
        f"({d['license']}). Train {d['n_train']} / validation {d['n_val']} / test {d['n_test']} lines; "
        f"the test period contains {d['n_test_attack']} attack lines (prevalence {d['test_prevalence']:.3f}), "
        f"so precision and PR-AUC are inflated by the base rate (a random scorer has PR-AUC = "
        f"{d['test_prevalence']:.3f}; base rate is 0 in train and validation by construction). "
        f'"FPR (other hosts)" is the alert rate on {d["n_other_hosts_benign_test"]} unlabelled, benign-by-convention '
        f"test-day lines from two other web vhosts. Threshold: "
        f"{p['threshold_quantile']:.0%} quantile of benign validation scores. Mean ± std over "
        f"{len(p['seeds'])} seeds; the rule baseline is deterministic.",
        "",
    ]
    for variant, res in metrics["results"].items():
        info = p["variants"][variant]
        tag = (
            "post-hoc, in-sample design decision"
            if info["post_hoc"]
            else "pre-registered, held-out"
        )
        lines += [f"**Variant `{variant}`** ({tag})", ""]
        lines += [
            "| Model | Precision | Recall | F1 | PR-AUC | FPR (test benign) | FPR (other hosts) | Recall on low-rate attacks [Wilson 95%] |",
            "|---|---|---|---|---|---|---|---|",
        ]
        for name in MAIN_MODELS:
            r = res[name]
            lr = r["recall_low_rate_attacks"]
            if lr["recall_mean"] is None:
                low = "n/a"
            else:
                lo, hi = lr["wilson95"]
                low = f"{lr['recall_mean']:.3f} [{lo:.2f}, {hi:.2f}] (n={lr['n']})"
            fo = r["fpr_other_hosts"]
            other = f"{fo['mean']:.4f} (n={fo['n']})"
            lines.append(
                f"| {name} | {_cell(r, 'precision')} | {_cell(r, 'recall')} | {_cell(r, 'f1')} | "
                f"{_cell(r, 'pr_auc')} | {_cell(r, 'fpr')} | {other} | {low} |"
            )
        lines.append("")
    if benchmark:
        hw = benchmark["hardware"]["cpu"]
        lines += [
            f"Throughput (`make benchmark`, {hw}, Python {benchmark['python']}, single process, "
            f"parse + features + score only; no HTTP or database): "
            f"{benchmark['events_per_second']:.0f} events/s, latency p50 "
            f"{benchmark['latency_ms_p50']:.1f} ms / p95 {benchmark['latency_ms_p95']:.1f} ms.",
            "",
        ]
    lines += [END]
    return "\n".join(lines)


def update(readme: Path, results: Path) -> str:
    """Return README text with the results block refreshed."""
    metrics = json.loads((results / "metrics.json").read_text())
    bench_path = results / "benchmark.json"
    bench = json.loads(bench_path.read_text()) if bench_path.exists() else None
    text = readme.read_text()
    a, b = text.index(START), text.index(END) + len(END)
    return text[:a] + render(metrics, bench) + text[b:]


def main(argv: list[str] | None = None) -> int:
    """CLI: rewrite README.md, or with ``--check`` fail if it is stale."""
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--readme", type=Path, default=Path("README.md"))
    ap.add_argument("--results", type=Path, default=Path("results"))
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args(argv)
    new = update(args.readme, args.results)
    if args.check:
        return 0 if new == args.readme.read_text() else 1
    args.readme.write_text(new)
    return 0


if __name__ == "__main__":
    sys.exit(main())
